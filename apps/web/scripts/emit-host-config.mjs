#!/usr/bin/env node
/**
 * Writes the host-level header configuration for the static deploy.
 *
 * The trap this exists to avoid: **`headers()` in next.config.mjs does nothing under
 * `output: 'export'`.** Next says so in a build warning that is easy to scroll past.
 * A static export is a directory of files; there is no Next server left to add a
 * header, so the Content-Security-Policy that the config so carefully assembles is
 * simply absent in production unless the CDN is told about it separately.
 *
 * Rather than maintain that list twice and let the copies drift, this script imports
 * next.config.mjs and asks it for the real header list, then renders it into:
 *
 *   public/_headers   Cloudflare Pages and Netlify (copied to out/_headers on export)
 *   vercel.json       Vercel
 *
 * docs/DEPLOY.md carries the nginx and Caddy equivalents, which cannot be generated
 * because they live in server config rather than in the published directory.
 *
 * Run by `npm run prebuild` in apps/web.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const WEB = path.resolve(HERE, '..');

const { default: nextConfig } = await import(path.join(WEB, 'next.config.mjs'));

const rules = typeof nextConfig.headers === 'function' ? await nextConfig.headers() : [];
const globalRule = rules.find((r) => r.source === '/:path*') ?? rules[0];
const securityHeaders = globalRule?.headers ?? [];

if (securityHeaders.length === 0) {
  console.error('emit-host-config: next.config.mjs returned no headers — refusing to write an empty policy.');
  process.exit(1);
}

/* ------------------------------------------------------------------ caching -- */

/**
 * Immutable caching is a promise that a URL's bytes will never change. It is true for
 * both paths below and false for everything else:
 *
 *   /_next/static/*  Next puts a content hash in every filename.
 *   /wasm/<sha256>/* scripts/prepare-assets.mjs puts the binary's own digest in the
 *                    directory name, so a rebuilt extractor is a new URL.
 *
 * The HTML must not be cached this way: it is the thing that points at the hashed
 * URLs, so if it goes stale everything else does too. It revalidates on every view,
 * which for a page this small costs a 304.
 */
const CACHE_RULES = [
  { path: '/_next/static/*', value: 'public, max-age=31536000, immutable' },
  { path: '/wasm/*', value: 'public, max-age=31536000, immutable' },
  { path: '/licences/*', value: 'public, max-age=3600' },
  { path: '/*.html', value: 'public, max-age=0, must-revalidate' },
  { path: '/', value: 'public, max-age=0, must-revalidate' },
];

/**
 * Most CDNs already map .wasm correctly, but a wrong Content-Type is not a cosmetic
 * problem here: `WebAssembly.instantiateStreaming` refuses anything that is not
 * exactly `application/wasm`, and the failure is a console error on a page whose only
 * feature is the thing that failed. Stating it costs nothing and removes the class.
 */
const MIME_RULES = [
  { path: '/wasm/*.wasm', header: 'Content-Type', value: 'application/wasm' },
  { path: '/wasm/*/dist/pubshift.wasm', header: 'Content-Type', value: 'application/wasm' },
];

/* ----------------------------------------------------------------- _headers -- */

const lines = [
  '# GENERATED by scripts/emit-host-config.mjs — edit next.config.mjs instead.',
  '#',
  '# Cloudflare Pages and Netlify both read this file from the root of the published',
  '# directory. Next copies public/ into out/ verbatim, so it lands in the right place.',
  '',
  '/*',
  ...securityHeaders.map((h) => `  ${h.key}: ${h.value}`),
  '',
];

for (const rule of CACHE_RULES) {
  lines.push(rule.path, `  Cache-Control: ${rule.value}`, '');
}
for (const rule of MIME_RULES) {
  lines.push(rule.path, `  ${rule.header}: ${rule.value}`, '');
}

mkdirSync(path.join(WEB, 'public'), { recursive: true });
writeFileSync(path.join(WEB, 'public', '_headers'), lines.join('\n'));

/* --------------------------------------------------------------- vercel.json -- */

const vercel = {
  $schema: 'https://openapi.vercel.sh/vercel.json',
  // GENERATED — see scripts/emit-host-config.mjs
  headers: [
    { source: '/(.*)', headers: securityHeaders },
    ...CACHE_RULES.filter((r) => r.path.includes('*')).map((r) => ({
      source: r.path.replace('/*', '/(.*)'),
      headers: [{ key: 'Cache-Control', value: r.value }],
    })),
    {
      source: '/wasm/(.*).wasm',
      headers: [{ key: 'Content-Type', value: 'application/wasm' }],
    },
  ],
};

writeFileSync(path.join(WEB, 'vercel.json'), `${JSON.stringify(vercel, null, 2)}\n`);

console.log(`emit-host-config: ${securityHeaders.length} security headers -> public/_headers, vercel.json`);
